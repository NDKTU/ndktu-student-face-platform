import DOMPurify from 'dompurify';

/**
 * Единая очистка HTML, пришедшего с бэкенда.
 *
 * Тексты вопросов и вариантов ответа хранятся как HTML (их пишет jodit), поэтому
 * выводятся через dangerouslySetInnerHTML — и каждое такое место обязано проходить
 * через эту функцию. Автор вопроса — преподаватель, но список вопросов открывают
 * и администраторы, то есть неочищенная вставка выполнялась бы у пользователя
 * с более широкими правами, чем у автора.
 *
 * Профиль `html` не включает MathML: когда в вопросы добавят формулы, сюда нужно
 * дописать `mathMl: true`, иначе формулы будут молча вырезаться при выводе.
 */
export const sanitizeHtml = (html: string): string =>
    DOMPurify.sanitize(html ?? '', { USE_PROFILES: { html: true } });
