"""Проверка роли «администратор» — одна на всё приложение.

Раньше вопрос «этот пользователь админ?» решался в двух несовместимых
вариантах. Гейт прав сравнивал точно (`role.name == "Admin"`,
`core/dependencies/role_checker.py`), а репозитории — без учёта регистра
(`role.name.lower() == "admin"`, десять мест). Роль с именем `admin` в нижнем
регистре из-за этого получала университетскую видимость данных, но не обход
проверки прав: половина привилегий без второй половины, и ни одного места, где
это было бы видно.

Здесь выбрано точное сравнение — то есть более узкое из двух. Опереться есть на
что: `sync_admin_role` при каждом старте гарантирует роль ровно с именем
`ADMIN_ROLE_NAME`, а уникальность имён ролей проверяется без учёта регистра,
поэтому завести рядом `admin` больше нельзя.
"""

from app.core.lifespan.defaults import ADMIN_ROLE_NAME


def is_admin(user) -> bool:
    """True, если у пользователя есть роль администратора.

    `user` — ORM-объект `User` с загруженными `roles`.
    """
    return any(role.name == ADMIN_ROLE_NAME for role in user.roles)
