"""Защита строк, которыми владеет внешняя система.

Как только справочник переведён в режим зеркала, править его руками нельзя:
следующий прогон синхронизации молча вернёт прежние значения, и расхождение
обнаружится в самый неподходящий момент. Поэтому мутации таких строк
отклоняются явной ошибкой, а не «принимаются» с последующим откатом.
"""

from fastapi import HTTPException, status

#: Человекочитаемые названия источников для текста ошибки.
SOURCE_LABELS = {
    "eduplan": "EduPlan (EPOS)",
    "hemis": "HEMIS",
}


def ensure_editable(row, entity: str) -> None:
    """Бросает 409, если строка принадлежит внешней системе.

    ``entity`` — название сущности в родительном падеже для сообщения:
    «факультета», «кафедры», «группы».
    """
    source = getattr(row, "external_source", None)
    if not source:
        return

    label = SOURCE_LABELS.get(source, source)
    raise HTTPException(
        status_code=status.HTTP_409_CONFLICT,
        detail=(
            f"Запись {entity} синхронизируется из {label} и не редактируется вручную. "
            f"Измените данные в {label} — они приедут при следующей синхронизации."
        ),
    )
