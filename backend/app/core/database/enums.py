"""ENUM-типы, общие для нескольких моделей.

Здесь живут только те словари, которыми пользуется больше одной таблицы. Если
значение принадлежит одной модели — оно объявляется рядом с ней (так сделан
`education_form` в `organization_structure/group/model.py`).

Правило то же, что и для остальных словарей проекта: в базе — настоящий
PostgreSQL ENUM, во входных схемах — Pydantic `Literal`. Значения дублируются
и меняются вместе; собрать `Literal` из кортежа нельзя, ему нужны литералы.
"""

from sqlalchemy import Enum

# Пол. Общий для employees и students: это одно и то же поле у одного и того же
# человека, и держать два несвязанных словаря значило бы позволить им разойтись.
#
# Из HEMIS приходит кодом (11 → Erkak, 12 → Ayol), сопоставление — в
# HEMIS_DICTIONARIES (`auth/student/repository.py`), поэтому строгий ENUM
# импорту не мешает.
GENDERS = ("Erkak", "Ayol")

gender_enum = Enum(*GENDERS, name="gender")
